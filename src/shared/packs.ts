/** Bounded declarative projection for overview clients; raw user files stay out. */
export interface PackGuidance {
  workflow: string
  tools: string[]
  evidence: string
  permissions: string
  budget: { maxAttempts?: number; note?: string }
  /** Use butler_pack show for the complete declaration when this is true. */
  truncated?: boolean
}

export interface PackSummary {
  id: string
  title: string
  enabled: boolean
  source: PackSource
  cost_class: PackCostClass
  broken?: string
  /** Optional so older read-only overview payloads remain renderable. */
  boundary?: PackBoundary
  guidance?: PackGuidance
}

/** Label the declaration without converting it into a total-cost estimate. */
export function packCostLabel(cost: PackCostClass): string {
  if (cost === 'free') return '声明：无付费外部服务预期'
  if (cost === 'local') return '声明：本地服务预期'
  if (cost === 'paid') return '声明：可能使用付费服务'
  return '服务成本类别未知'
}
