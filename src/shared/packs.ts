/** Pack declarations are advice; this read model never asserts a live grant. */
export type PackCostClass = 'free' | 'local' | 'paid' | 'unknown'
/**
 * Where a pack came from.
 *
 * - `builtin`: shipped in the kernel (host/packs.ts);
 * - `user`: a markdown file under `vault/packs/<id>.md`, editable by the owner;
 * - `extension`: registered at runtime by another bundle through the
 *   `butlerExtensions` service (`schemaVersion: 1`, see docs/extension-api.md).
 *   Its lifetime follows the registration, not `state/packs.json`.
 */
export type PackSource = 'builtin' | 'user' | 'extension'

/**
 * Pack ids the kernel owns; an extension pack may not reuse one.
 *
 * This mirrors the `BUILTIN` table in `host/packs.ts` for callers that validate
 * a manifest without a host (the public `validatePackManifest`), while the
 * runtime registry passes the live `BUILTIN_PACK_IDS` instead. A test asserts
 * both lists agree, so adding a built-in pack here and in `host/packs.ts` is
 * one change, not two truths.
 */
export const KERNEL_PACK_IDS: readonly string[] = Object.freeze(['daily', 'life', 'documents', 'study', 'research', 'nature'])

/** Generated by the kernel, never parsed from a user pack's front matter. */
