/**
 * The public extension contract: capability packs and channel adapters.
 *
 * This module is deliberately pure: **no I/O, no host services, no Cordis
 * imports** (the only imports are sibling declarations/constants from
 * `shared/packs.ts`, which is itself pure). It is the single place that decides
 * what a third-party bundle may declare, so that a manifest accepted here is
 * accepted by the runtime registry and by nothing else.
 *
 * What the contract promises, and what it refuses to promise:
 *
 * - **`schemaVersion` is a gate, not a hint.** Every pack manifest and channel
 *   adapter must carry `schemaVersion: 1`. A missing or different version is a
 *   validation error naming the expected value; nothing is silently upgraded or
 *   downgraded.
 * - **Packs declare advice.** `tools` are recommendations, not an allowlist;
 *   `permissions` is guidance, not an approval; `budget` is retry advice, not a
 *   hard budget; `cost_class` is a service class, not a money cap. The kernel
 *   boundary (`PACK_BOUNDARY` in `shared/packs.ts`) is generated by the kernel
 *   and is never read from a manifest.
 * - **Channels are declared, not driven.** Validation checks that `isReady`
 *   and `send` exist and are functions; it never calls either, never picks a
 *   destination, never reads credentials, and grants no permission. Registering
 *   an adapter does not connect anything or take over delivery.
 *
 * @module @dsh-external/dsh-butler/extension
 */
import type { PackBoundary, PackCostClass } from './packs.ts'
import { KERNEL_PACK_IDS } from './packs.ts'

/** The only manifest/adapter schema version this kernel accepts. */
export const BUTLER_EXTENSION_SCHEMA_VERSION = 1 as const

/** Cordis service name sibling bundles resolve through `ctx.get(..., false)`. */
export const BUTLER_EXTENSIONS_SERVICE = 'butlerExtensions'

/**
 * Declared limits, mirrored in documentation and enforced by the validators.
 *
 * They are part of the `schemaVersion: 1` contract: changing one of them is a
 * compatibility change, so it must come with a version bump and a migration
 * note rather than a quiet edit.
 */
export const EXTENSION_LIMITS = Object.freeze({
  /** Pack and channel ids: a lowercase letter, then 1–31 lowercase/digit/hyphen. */
  idPattern: '^[a-z][a-z0-9-]{1,31}$',
  idMin: 2,
  idMax: 32,
  titleMin: 1,
  titleMax: 64,
  triggersMax: 32,
  triggerMax: 32,
  instructionsMax: 8000,
  evidenceMax: 2000,
  permissionsMax: 2000,
  toolsMax: 24,
  toolNameMax: 160,
  budgetAttemptsMin: 1,
  budgetAttemptsMax: 10,
  budgetNoteMax: 500,
})

/** Retry advice declared by a pack; never a runtime hard budget. */
export interface PackBudgetDeclaration {
  /** Suggested attempts for one piece of work (1–10). */
  maxAttempts?: number
  /** Free-text note shown with the suggestion (≤ 500 characters). */
  note?: string
}

/**
 * A capability pack manifest, exactly as a third party declares it.
 *
 * `cost_class` and `budget` are optional; validation normalizes them to
 * `'unknown'` and `{}` respectively. `boundary` is *not* a manifest field: the
 * kernel generates it when the pack is registered.
 */
export interface PackManifest {
  schemaVersion: 1
  id: string
  title: string
  triggers: string[]
  instructions: string
  evidence: string
  permissions: string
  tools?: string[]
  budget?: PackBudgetDeclaration
  cost_class?: PackCostClass
}

/**
 * A validated, normalized manifest: every field is complete and frozen.
 *
 * This is what the registry stores and what the read model receives; callers
 * cannot mutate a registered pack through the object returned by `list()`.
 */
export interface ResolvedPackManifest {
  readonly schemaVersion: 1
  readonly id: string
  readonly title: string
  readonly triggers: readonly string[]
  readonly instructions: string
  readonly evidence: string
  readonly permissions: string
  readonly tools: readonly string[]
  readonly budget: Readonly<PackBudgetDeclaration>
  readonly cost_class: PackCostClass
}

/** Options for {@link validatePackManifest}. */
export interface PackManifestValidationOptions {
  /**
   * Kernel-owned ids an extension pack may not reuse.
   *
   * Defaults to {@link KERNEL_PACK_IDS}; the runtime registry passes its live
   * built-in id list so a new shipped pack cannot be shadowed even if the
   * shared snapshot lags behind.
   */
  kernelPackIds?: readonly string[]
}

/** A validated pack as the registry stores it and `list()` reports it. */
export interface ExtensionPackEntry extends ResolvedPackManifest {
  /** Registered at runtime through the `butlerExtensions` service. */
  readonly source: 'extension'
  /** Lifetime follows the registration; `state/packs.json` cannot switch it. */
  readonly enabled: true
  /** Generated by the kernel (`PACK_BOUNDARY`), never read from the manifest. */
  readonly boundary: PackBoundary
}

/** Where a channel adapter says a message should go. Chosen by the caller. */
export interface ChannelDestination {
  /** Stable destination id in the adapter's own namespace. */
  id: string
  /** Adapter-defined kind (chat, thread, mailbox, ...). */
  kind: string
}

/** The only payload shape `schemaVersion: 1` defines. */
export interface ChannelPayload {
  text: string
}

/** Result of one `send`; failures must say why. */
export interface ChannelSendResult {
  ok: boolean
  /** Platform receipt, when the adapter actually delivered. */
  receiptId?: string
  /** Failure reason; required by convention when `ok` is false. */
  reason?: string
}

/**
 * Declared limits of an adapter (pure declaration).
 *
 * The kernel does not interpret these values; it only reports them. An adapter
 * that wants a limit enforced must enforce it itself.
 */
export interface ChannelLimits {
  readonly [key: string]: unknown
}

/**
 * A channel adapter, exactly as a third party declares it.
 *
 * Registering one does **not** connect it, pick destinations, read credentials
 * or route anything through it: the butler only knows the adapter exists and
 * may report its `id`/`title`/`limits`. Any actual send is initiated by the
 * host that owns the adapter, with its own authorization.
 */
export interface ButlerChannelAdapter {
  schemaVersion: 1
  id: string
  title: string
  /** Pure readiness report, never called by validation. */
  isReady(): boolean
  /** Actual delivery, never called by validation or by the registry. */
  send(destination: ChannelDestination, payload: ChannelPayload): Promise<ChannelSendResult>
  limits?: ChannelLimits
}

/** A validated adapter as the registry stores it and `list()` reports it. */
export interface ResolvedChannelAdapter {
  readonly schemaVersion: 1
  readonly id: string
  readonly title: string
  readonly isReady: () => boolean
  readonly send: (destination: ChannelDestination, payload: ChannelPayload) => Promise<ChannelSendResult>
  readonly limits?: ChannelLimits
}

/** A registered adapter plus where it came from. */
export interface ExtensionChannelEntry extends ResolvedChannelAdapter {
  readonly source: 'extension'
}

/** Read-only inventory returned by `list()`. Stable field names. */
export interface ButlerExtensionList {
  readonly packs: readonly ExtensionPackEntry[]
  readonly channels: readonly ExtensionChannelEntry[]
}

/**
 * The `butlerExtensions` Cordis service, as sibling bundles see it.
 *
 * Obtain it with `ctx.get('butlerExtensions', false)` (a lenient lookup, so a
 * host without the butler simply gets `undefined`) and register inside
 * `ctx.effect` so unloading the plugin releases the registrations.
 */
export interface ButlerExtensionService {
  readonly schemaVersion: 1
  /** Validate and publish one capability pack; returns an idempotent disposer. */
  registerPack(manifest: PackManifest): () => void
  /** Validate and publish one channel adapter; returns an idempotent disposer. */
  registerChannel(adapter: ButlerChannelAdapter): () => void
  /** Snapshot of everything registered right now. */
  list(): ButlerExtensionList
}

/** Raise a validation error whose message is always actionable and prefixed. */
function fail(message: string): never {
  throw new Error(`管家扩展：${message}`)
}

/** Human-readable type name used in diagnostics. */
function describeValue(value: unknown): string {
  if (value === null) return 'null'
  if (Array.isArray(value)) return '数组'
  if (typeof value === 'string') return `字符串（"${value.slice(0, 40)}"）`
  if (typeof value === 'number') return `数字（${String(value)}）`
  if (typeof value === 'boolean') return `布尔值（${String(value)}）`
  if (typeof value === 'function') return '函数'
  if (typeof value === 'object') return '对象'
  return String(value)
}

/** Ensure a value is a plain object (not null, not an array, not a function). */
function plainObject(value: unknown, label: string): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    fail(`${label} 必须是普通对象，收到 ${describeValue(value)}。`)
  }
  return value as Record<string, unknown>
}

/**
 * Enforce the version gate before anything else.
 *
 * A missing version is reported as missing (not as "unknown version 1"), and a
 * different one names both the expected and the received value, so a third
 * party never has to guess why validation failed.
 */
function requireSchemaVersion(value: unknown, label: string): 1 {
  if (value === undefined) {
    fail(`${label} 缺少 schemaVersion；必须显式写 schemaVersion: ${BUTLER_EXTENSION_SCHEMA_VERSION}（当前唯一支持的版本）。`)
  }
  if (value !== BUTLER_EXTENSION_SCHEMA_VERSION) {
    fail(`${label} 的 schemaVersion 必须是 ${BUTLER_EXTENSION_SCHEMA_VERSION}，收到 ${describeValue(value)}；版本不匹配不做静默降级。`)
  }
  return BUTLER_EXTENSION_SCHEMA_VERSION
}

/** Read one required/optional non-empty string field. */
function textField(value: unknown, label: string, min: number, max: number): string {
  if (typeof value !== 'string') fail(`${label} 必须是字符串，收到 ${describeValue(value)}。`)
  const text = value.trim()
  if (text.length < min) fail(`${label} 不能为空（要求 ${min}..${max} 个字符）。`)
  if (text.length > max) fail(`${label} 太长了：${text.length} 个字符，上限 ${max}。`)
  return text
}

/** Read one string array field with per-item and total limits. */
function textList(value: unknown, label: string, itemMin: number, itemMax: number, maxItems: number, required: boolean): string[] {
  if (value === undefined) {
    if (!required) return []
    fail(`${label} 必填（可以是空数组，0..${maxItems} 个字符串）。`)
  }
  if (!Array.isArray(value)) fail(`${label} 必须是字符串数组，收到 ${describeValue(value)}。`)
  if (value.length > maxItems) fail(`${label} 最多 ${maxItems} 项，收到 ${value.length} 项。`)
  return value.map((item, index) => textField(item, `${label}[${index}]`, itemMin, itemMax))
}

/** Validate a pack id (also used for channel ids) and its kernel reservation. */
function extensionId(value: unknown, label: string, kernelPackIds?: readonly string[]): string {
  const id = textField(value, label, EXTENSION_LIMITS.idMin, EXTENSION_LIMITS.idMax)
  if (!new RegExp(EXTENSION_LIMITS.idPattern).test(id)) {
    fail(`${label} 必须是 ${EXTENSION_LIMITS.idPattern}（小写字母开头，只含小写字母/数字/短横线，2..32 个字符），收到 "${id}"。`)
  }
  const kernel = kernelPackIds ?? KERNEL_PACK_IDS
  if (kernel.includes(id)) {
    fail(`${label} "${id}" 已被内核内置包占用（来源：builtin）；扩展包不能复用内置 id，请换一个 id。`)
  }
  return id
}

/** Validate the optional `budget` declaration. */
function budgetField(value: unknown): PackBudgetDeclaration {
  if (value === undefined) return {}
  const budget = plainObject(value, '能力包 manifest 的 budget')
  for (const key of Object.keys(budget)) {
    if (key !== 'maxAttempts' && key !== 'note') {
      fail(`能力包 manifest 的 budget 含 schemaVersion 1 未声明的字段 "${key}"；只接受 maxAttempts、note。`)
    }
  }
  const resolved: PackBudgetDeclaration = {}
  if (budget.maxAttempts !== undefined) {
    if (!Number.isInteger(budget.maxAttempts)) {
      fail(`能力包 manifest 的 budget.maxAttempts 必须是整数，收到 ${describeValue(budget.maxAttempts)}。`)
    }
    const attempts = budget.maxAttempts as number
    if (attempts < EXTENSION_LIMITS.budgetAttemptsMin || attempts > EXTENSION_LIMITS.budgetAttemptsMax) {
      fail(`能力包 manifest 的 budget.maxAttempts 必须在 ${EXTENSION_LIMITS.budgetAttemptsMin}..${EXTENSION_LIMITS.budgetAttemptsMax} 之间，收到 ${attempts}。`)
    }
    resolved.maxAttempts = attempts
  }
  if (budget.note !== undefined) {
    resolved.note = textField(budget.note, '能力包 manifest 的 budget.note', 1, EXTENSION_LIMITS.budgetNoteMax)
  }
  return Object.freeze(resolved)
}

/** Validate the optional `cost_class` declaration. */
function costClassField(value: unknown): PackCostClass {
  if (value === undefined) return 'unknown'
  if (value !== 'free' && value !== 'local' && value !== 'paid' && value !== 'unknown') {
    fail(`能力包 manifest 的 cost_class 必须是 free、local、paid 或 unknown，收到 ${describeValue(value)}。`)
  }
  return value
}

const PACK_MANIFEST_KEYS = Object.freeze([
  'schemaVersion', 'id', 'title', 'triggers', 'instructions', 'evidence', 'permissions', 'tools', 'budget', 'cost_class',
])

/**
 * Validate and normalize a capability pack manifest.
 *
 * Throws an `Error` whose message starts with `管家扩展：` and names the
 * expected schema version and field on failure. On success returns a frozen
 * manifest with `tools`, `budget` and `cost_class` normalized to their defaults.
 * @param input - untrusted manifest value, typically parsed JSON or a literal.
 * @param options - reserved kernel ids, for validators outside the host.
 * @returns the normalized, frozen manifest.
 */
export function validatePackManifest(input: unknown, options: PackManifestValidationOptions = {}): ResolvedPackManifest {
  const manifest = plainObject(input, '能力包 manifest')
  requireSchemaVersion(manifest.schemaVersion, '能力包 manifest')
  for (const key of Object.keys(manifest)) {
    if (!PACK_MANIFEST_KEYS.includes(key)) {
      fail(`能力包 manifest 含 schemaVersion 1 未声明的字段 "${key}"；允许的字段是：${PACK_MANIFEST_KEYS.join('、')}。`)
    }
  }
  const id = extensionId(manifest.id, '能力包 manifest 的 id', options.kernelPackIds)
  const title = textField(manifest.title, '能力包 manifest 的 title', EXTENSION_LIMITS.titleMin, EXTENSION_LIMITS.titleMax)
  const triggers = textList(manifest.triggers, '能力包 manifest 的 triggers', 1, EXTENSION_LIMITS.triggerMax, EXTENSION_LIMITS.triggersMax, true)
  const instructions = textField(manifest.instructions, '能力包 manifest 的 instructions', 1, EXTENSION_LIMITS.instructionsMax)
  const evidence = textField(manifest.evidence, '能力包 manifest 的 evidence', 1, EXTENSION_LIMITS.evidenceMax)
  const permissions = textField(manifest.permissions, '能力包 manifest 的 permissions', 1, EXTENSION_LIMITS.permissionsMax)
  const tools = textList(manifest.tools, '能力包 manifest 的 tools', 1, EXTENSION_LIMITS.toolNameMax, EXTENSION_LIMITS.toolsMax, false)
  const budget = budgetField(manifest.budget)
  const costClass = costClassField(manifest.cost_class)
  return Object.freeze({
    schemaVersion: BUTLER_EXTENSION_SCHEMA_VERSION,
    id,
    title,
    triggers: Object.freeze(triggers),
    instructions,
    evidence,
    permissions,
    tools: Object.freeze(tools),
    budget,
    cost_class: costClass,
  })
}

/**
 * Validate a channel adapter's declared shape.
 *
 * Only existence and type are checked: `send` and `isReady` are **not called**,
 * no destination is chosen and no credential is read. Extra own properties are
 * preserved by the adapter itself and ignored here (a class instance may carry
 * its own state); the `schemaVersion: 1` fields above are the whole contract.
 * @param input - untrusted adapter value.
 * @returns the validated adapter record (same function references).
 */
export function validateChannelAdapter(input: unknown): ResolvedChannelAdapter {
  const adapter = plainObject(input, '通道 adapter')
  requireSchemaVersion(adapter.schemaVersion, '通道 adapter')
  const id = extensionId(adapter.id, '通道 adapter 的 id')
  const title = textField(adapter.title, '通道 adapter 的 title', EXTENSION_LIMITS.titleMin, EXTENSION_LIMITS.titleMax)
  if (typeof adapter.isReady !== 'function') {
    fail(`通道 adapter 的 isReady 必须是函数（返回 boolean），收到 ${describeValue(adapter.isReady)}。`)
  }
  if (typeof adapter.send !== 'function') {
    fail(`通道 adapter 的 send 必须是函数（返回 Promise<{ok, receiptId?, reason?}>），收到 ${describeValue(adapter.send)}。`)
  }
  let limits: ChannelLimits | undefined
  if (adapter.limits !== undefined) {
    const declared = plainObject(adapter.limits, '通道 adapter 的 limits')
    limits = Object.freeze({ ...declared })
  }
  return Object.freeze({
    schemaVersion: BUTLER_EXTENSION_SCHEMA_VERSION,
    id,
    title,
    isReady: adapter.isReady as () => boolean,
    send: adapter.send as (destination: ChannelDestination, payload: ChannelPayload) => Promise<ChannelSendResult>,
    ...(limits === undefined ? {} : { limits }),
  })
}
